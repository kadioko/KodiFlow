export type TranslationKey = keyof typeof translations.en

export function translate(key: TranslationKey, language: LanguageCode = 'en', values: Record<string, string | number> = {}) {
  const message = translations[language][key] || translations.en[key]
  return message.replace(/\{(\w+)\}/g, (placeholder, name: string) => String(values[name] ?? placeholder))
}

export function normalizeLanguage(value: unknown): LanguageCode {
  return value === 'sw' ? 'sw' : 'en'
}
